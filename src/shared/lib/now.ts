/**
 * Текущий месяц в формате YYYY-MM. Единая точка получения «сейчас»:
 * и предрендер, и гидрация считают стаж от одного значения.
 *
 * Без явного аргумента функция намеренно берёт не часы посетителя, а
 * `__BUILD_MONTH__` — константу, которую `vite.config.ts` вшивает в бандл
 * через `define` в момент сборки (и в клиентский, и в SSR-бандл — они
 * собираются этим же конфигом в рамках одного `npm run build`). Если брать
 * реальную дату браузера, то клиент и статическая разметка из
 * `scripts/prerender.mjs`, собранные в одном месяце, а открытые в другом,
 * посчитают разный стаж — React 19 при гидратации увидит несовпадение
 * текстовых узлов, отбросит предрендер и перерисует всё на клиенте, и вся
 * цель предрендера (LCP, работа без JS, SEO) для этого рендера пропадёт.
 * Актуальность числа поддерживается не часами посетителя, а ежемесячной
 * пересборкой по расписанию (`.github/workflows/deploy.yml`).
 *
 * `__BUILD_MONTH__` подставляется только при `command === 'build'` — на
 * dev-сервере и в vitest её нет, и функция берёт реальную дату. Это не
 * баг и не повод возвращать сюда `new Date()` по умолчанию: тесты на это
 * поведение — `now.test.ts`.
 */
export function currentMonthIso(date?: Date): string {
  if (date === undefined) {
    if (typeof __BUILD_MONTH__ === 'string') {
      return __BUILD_MONTH__;
    }
    date = new Date();
  }
  const month = String(date.getMonth() + 1).padStart(2, '0');
  return `${date.getFullYear()}-${month}`;
}
